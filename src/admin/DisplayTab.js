import { Button, RadioControl, RangeControl, SelectControl, TextControl, ToggleControl, Spinner } from '@wordpress/components';
import { useEffect, useMemo, useState } from '@wordpress/element';
import { __ } from '@wordpress/i18n';
import { request } from '../core3/api';
import { debounce } from './utils';

const COLORS = () => [
	[ 'accent', __( 'Accent', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'background', __( 'Background', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'text', __( 'Text', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'border', __( 'Border', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'positive', __( 'Positive', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'neutral', __( 'Neutral', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'negative', __( 'Negative', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
];

const TOGGLES = () => [
	[ 'show_summary', __( 'Summary paragraph', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_pros_cons', __( 'Pros & cons', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_sentiment', __( 'Sentiment bar', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_scores', __( 'Quality, value & fit scores', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_keywords', __( 'Keywords & themes', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_count', __( '“Based on N reviews”', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
	[ 'show_disclaimer', __( '“Generated by AI” note', 'dev3-ai-review-summarizer-for-woocommerce' ) ],
];

export const POSITIONS = () => [
	{ value: 'above_reviews', label: __( 'Above the reviews list', 'dev3-ai-review-summarizer-for-woocommerce' ) },
	{ value: 'add_to_cart', label: __( 'Below the Add to cart button', 'dev3-ai-review-summarizer-for-woocommerce' ) },
	{ value: 'tab', label: __( 'Own “Review summary” tab', 'dev3-ai-review-summarizer-for-woocommerce' ) },
	{ value: 'off', label: __( 'Off (shortcode / block only)', 'dev3-ai-review-summarizer-for-woocommerce' ) },
];

export default function DisplayTab( { settings, save } ) {
	const [ form, setForm ] = useState( settings.display );
	const [ html, setHtml ] = useState( null );
	const [ products, setProducts ] = useState( [] );
	const [ productId, setProductId ] = useState( 0 );
	const [ saving, setSaving ] = useState( false );

	useEffect( () => {
		request( 'products?per_page=100' )
			.then( ( res ) => setProducts( res.items.filter( ( p ) => p.summary ) ) )
			.catch( () => {} );
	}, [] );

	const refresh = useMemo(
		() =>
			debounce( ( display, id ) => {
				request( 'preview', { method: 'POST', data: { display, product_id: id } } )
					.then( ( r ) => setHtml( r.html ) )
					.catch( () => {} );
			}, 250 ),
		[]
	);
	useEffect( () => {
		refresh( form, productId );
	}, [ form, productId, refresh ] );

	const set = ( key ) => ( value ) => setForm( { ...form, [ key ]: value } );
	const dirty = JSON.stringify( form ) !== JSON.stringify( settings.display );

	return (
		<div className="dev3rs-display">
			<div className="dev3rs-display__form">
				<div className="dev3rs-card">
					<h2>{ __( 'Placement', 'dev3-ai-review-summarizer-for-woocommerce' ) }</h2>
					<p className="description">{ __( 'Where the summary appears on single product pages. Works with classic and block themes.', 'dev3-ai-review-summarizer-for-woocommerce' ) }</p>
					<SelectControl __nextHasNoMarginBottom label={ __( 'Position', 'dev3-ai-review-summarizer-for-woocommerce' ) } value={ form.position } options={ POSITIONS() } onChange={ set( 'position' ) } />
					<p className="description dev3rs-mt-2">
						{ __( 'Anywhere else: shortcode', 'dev3-ai-review-summarizer-for-woocommerce' ) } <code>[dev3rs_summary id="123"]</code> { __( 'or the “AI Review Summary” block.', 'dev3-ai-review-summarizer-for-woocommerce' ) }
					</p>
				</div>
				<div className="dev3rs-card">
					<h2>{ __( 'Layout & content', 'dev3-ai-review-summarizer-for-woocommerce' ) }</h2>
					<RadioControl
						label={ __( 'Layout', 'dev3-ai-review-summarizer-for-woocommerce' ) }
						selected={ form.layout }
						options={ [
							{ value: 'card', label: __( 'Card', 'dev3-ai-review-summarizer-for-woocommerce' ) },
							{ value: 'compact', label: __( 'Compact', 'dev3-ai-review-summarizer-for-woocommerce' ) },
						] }
						onChange={ set( 'layout' ) }
					/>
					<div className="dev3rs-toggles">
						{ TOGGLES().map( ( [ key, label ] ) => (
							<ToggleControl __nextHasNoMarginBottom key={ key } label={ label } checked={ !! form[ key ] } onChange={ set( key ) } />
						) ) }
					</div>
					<div className="dev3rs-edit__grid">
						<TextControl __nextHasNoMarginBottom label={ __( 'Heading', 'dev3-ai-review-summarizer-for-woocommerce' ) } placeholder={ __( 'AI review summary', 'dev3-ai-review-summarizer-for-woocommerce' ) } value={ form.heading } onChange={ set( 'heading' ) } />
						<TextControl __nextHasNoMarginBottom label={ __( 'Tab title', 'dev3-ai-review-summarizer-for-woocommerce' ) } placeholder={ __( 'Review summary', 'dev3-ai-review-summarizer-for-woocommerce' ) } value={ form.tab_title } onChange={ set( 'tab_title' ) } />
						<TextControl __nextHasNoMarginBottom label={ __( 'Pros title', 'dev3-ai-review-summarizer-for-woocommerce' ) } placeholder={ __( 'What buyers love', 'dev3-ai-review-summarizer-for-woocommerce' ) } value={ form.pros_title } onChange={ set( 'pros_title' ) } />
						<TextControl __nextHasNoMarginBottom label={ __( 'Cons title', 'dev3-ai-review-summarizer-for-woocommerce' ) } placeholder={ __( 'Things to consider', 'dev3-ai-review-summarizer-for-woocommerce' ) } value={ form.cons_title } onChange={ set( 'cons_title' ) } />
					</div>
				</div>
				<div className="dev3rs-card">
					<h2>{ __( 'Colours', 'dev3-ai-review-summarizer-for-woocommerce' ) }</h2>
					<div className="dev3rs-colors">
						{ COLORS().map( ( [ key, label ] ) => (
							<label key={ key } className="dev3rs-color">
								<input type="color" value={ form[ key ] } onChange={ ( e ) => set( key )( e.target.value ) } />
								<span>{ label }</span>
								<code>{ form[ key ] }</code>
							</label>
						) ) }
					</div>
					<RangeControl __nextHasNoMarginBottom label={ __( 'Corner radius (px)', 'dev3-ai-review-summarizer-for-woocommerce' ) } min={ 0 } max={ 32 } value={ Number( form.radius ) } onChange={ set( 'radius' ) } />
				</div>
				<div className="dev3rs-savebar">
					<Button
						variant="primary"
						className="dev3rs-save-display"
						isBusy={ saving }
						disabled={ saving || ! dirty }
						onClick={ () => {
							setSaving( true );
							save( { display: form } ).finally( () => setSaving( false ) );
						} }
					>
						{ __( 'Save display settings', 'dev3-ai-review-summarizer-for-woocommerce' ) }
					</Button>
					{ dirty && (
						<Button variant="tertiary" onClick={ () => setForm( settings.display ) }>
							{ __( 'Discard changes', 'dev3-ai-review-summarizer-for-woocommerce' ) }
						</Button>
					) }
				</div>
			</div>
			<div className="dev3rs-display__preview">
				<div className="dev3rs-card dev3rs-sticky">
					<h2>{ __( 'Live preview', 'dev3-ai-review-summarizer-for-woocommerce' ) }</h2>
					<SelectControl
						__nextHasNoMarginBottom
						label={ __( 'Preview with', 'dev3-ai-review-summarizer-for-woocommerce' ) }
						value={ String( productId ) }
						options={ [ { value: '0', label: __( 'Sample summary', 'dev3-ai-review-summarizer-for-woocommerce' ) }, ...products.map( ( p ) => ( { value: String( p.id ), label: p.name } ) ) ] }
						onChange={ ( v ) => setProductId( parseInt( v, 10 ) || 0 ) }
					/>
					<div className="dev3rs-preview-frame dev3rs-mt-3">{ html === null ? <Spinner /> : <div dangerouslySetInnerHTML={ { __html: html } } /> }</div>
					<p className="description">{ __( 'Your theme’s fonts apply on the storefront.', 'dev3-ai-review-summarizer-for-woocommerce' ) }</p>
				</div>
			</div>
		</div>
	);
}
